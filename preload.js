'use strict';
const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('pet', {
  moveBy: (dx) => ipcRenderer.invoke('win:moveBy', dx),
  cursor: () => ipcRenderer.invoke('win:cursor'),
  dragStart: (sx, sy) => ipcRenderer.send('win:dragStart', sx, sy),
  dragMove: (sx, sy) => ipcRenderer.send('win:dragMove', sx, sy),
  dragEnd: () => ipcRenderer.send('win:dragEnd'),
  setMode: (m) => ipcRenderer.send('win:mode', m),
  setIgnore: (v) => ipcRenderer.send('win:ignore', v),
  peek: (on) => ipcRenderer.send('win:peek', on),
  contextMenu: (cfg) => ipcRenderer.send('win:menu', cfg),
  update: { check: () => ipcRenderer.invoke('update:check'), apply: () => ipcRenderer.invoke('update:apply'), version: () => ipcRenderer.invoke('app:version'), onAvailable: (cb) => ipcRenderer.on('update:available', (_e, p) => cb(p)), onProgress: (cb) => ipcRenderer.on('update:progress', (_e, p) => cb(p)) },
  bringToFront: () => ipcRenderer.send('win:front'),
  openSetup: () => ipcRenderer.send('app:openSetup'),
  setChatSize: (w, h) => ipcRenderer.invoke('win:chatSize', w, h),
  setWide: (px) => ipcRenderer.send('win:wide', px),
  media: { start: () => ipcRenderer.send('media:start'), stop: () => ipcRenderer.send('media:stop'), cmd: (a, v) => ipcRenderer.send('media:cmd', a, v), onState: (cb) => ipcRenderer.on('media:state', (_e, s) => cb(s)) },
  setScale: (s) => ipcRenderer.send('win:scale', s),
  setAlwaysOnTop: (v) => ipcRenderer.send('win:alwaysOnTop', v),
  login: { get: () => ipcRenderer.invoke('app:login:get'), set: (on) => ipcRenderer.invoke('app:login:set', on) },
  readClipboard: () => ipcRenderer.invoke('clipboard:read'),
  obsidian: { status: () => ipcRenderer.invoke('obsidian:status'), chooseVault: () => ipcRenderer.invoke('obsidian:chooseVault'), clear: () => ipcRenderer.invoke('obsidian:clear') },
  apps: { config: () => ipcRenderer.invoke('apps:config'), setMode: (m) => ipcRenderer.invoke('apps:setMode', m), setBlocked: (l) => ipcRenderer.invoke('apps:setBlocked', l), list: () => ipcRenderer.invoke('apps:list'), add: () => ipcRenderer.invoke('apps:add'), remove: (name) => ipcRenderer.invoke('apps:remove', name) },
  control: { get: () => ipcRenderer.invoke('control:get'), set: (patch) => ipcRenderer.invoke('control:set', patch), revoke: () => ipcRenderer.invoke('control:revoke'), onPanic: (cb) => ipcRenderer.on('control:panic', () => cb()) },
  diag: (model) => ipcRenderer.invoke('diag:run', model),
  onIdle: (cb) => ipcRenderer.on('idle:time', (_e, s) => cb(s)),
  onLanded: (cb) => ipcRenderer.on('pet:landed', () => cb()),
  onMenuAction: (cb) => ipcRenderer.on('menu:action', (_e, a) => cb(a)),
  onAgentStatus: (cb) => ipcRenderer.on('agent:status', (_e, s) => cb(s)),
  input: {
    enable: (on) => ipcRenderer.invoke('input:enable', on),
    onKey: (cb) => ipcRenderer.on('input:key', () => cb()),
    onWheel: (cb) => ipcRenderer.on('input:wheel', () => cb()),
  },
  state: {
    load: () => ipcRenderer.invoke('state:load'),
    save: (s) => ipcRenderer.send('state:save', s),
  },
  ai: {
    status: () => ipcRenderer.invoke('ai:status'),
    chat: (req) => ipcRenderer.invoke('ai:chat', req),
    abort: (id) => ipcRenderer.send('ai:abort', id),
    pull: (req) => ipcRenderer.invoke('ai:pull', req),
    onPull: (cb) => ipcRenderer.on('ai:pullProgress', (_e, p) => cb(p)),
    onToken: (cb) => ipcRenderer.on('ai:token', (_e, p) => cb(p)),
    onThinking: (cb) => ipcRenderer.on('ai:thinking', (_e, p) => cb(p)),
  },
});
